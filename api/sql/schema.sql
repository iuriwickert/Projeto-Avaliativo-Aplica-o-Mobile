CREATE DATABASE IF NOT EXISTS solis CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE solis;

CREATE TABLE IF NOT EXISTS users (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('user','admin') NOT NULL DEFAULT 'user',
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS revoked_tokens (
  jti CHAR(36) PRIMARY KEY,
  expires_at DATETIME NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_revoked_expiry (expires_at)
);
CREATE TABLE IF NOT EXISTS reference_parameters (
  `key` VARCHAR(64) PRIMARY KEY,
  value DECIMAL(12,5) NULL,
  unit VARCHAR(32) NOT NULL,
  source_name VARCHAR(190) NOT NULL,
  source_url VARCHAR(500) NOT NULL,
  region VARCHAR(160) NULL,
  consulted_on DATE NOT NULL,
  limitation TEXT NOT NULL,
  updated_by BIGINT UNSIGNED NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_reference_admin FOREIGN KEY (updated_by) REFERENCES users(id) ON DELETE SET NULL
);
CREATE TABLE IF NOT EXISTS simulations (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  user_id BIGINT UNSIGNED NOT NULL,
  title VARCHAR(120) NOT NULL,
  inputs JSON NOT NULL,
  result JSON NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_simulations_user_updated (user_id, updated_at),
  CONSTRAINT fk_simulation_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
